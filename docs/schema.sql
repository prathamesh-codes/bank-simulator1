
CREATE TABLE PGI_NETBANKING_SIMULATOR (
  ID                 NUMBER(19)     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  TXN_ID             VARCHAR2(50)   NOT NULL,
  BANK_ID            VARCHAR2(10)   NOT NULL,
  MERC_ID            VARCHAR2(30),
  TXN_STATUS         VARCHAR2(20)   NOT NULL,
  SELECTED_RESULT    VARCHAR2(10),
  FAILURE_REASON     VARCHAR2(500),
  BANK_REF           VARCHAR2(30),
  MERCHANT_CODE      VARCHAR2(30),
  TXN_AMOUNT         VARCHAR2(20),
  TXN_CURRENCY       VARCHAR2(5),
  RETURN_URL         VARCHAR2(1000),
  RAW_INIT_PARAMS    CLOB,
  DELAY_SECONDS      NUMBER(10),
  VERIFY_CALL_COUNT  NUMBER(10)     DEFAULT 0 NOT NULL,
  CREATED_AT         TIMESTAMP      NOT NULL,
  UPDATED_AT         TIMESTAMP      NOT NULL,
  CONSTRAINT UQ_PGI_NETBANKING_SIMULATOR_BANK_TXN UNIQUE (BANK_ID, TXN_ID)
);
